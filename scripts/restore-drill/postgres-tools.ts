import { execFile, spawn } from "node:child_process";
import { promisify } from "node:util";
import { open } from "node:fs/promises";

export async function postgresTools(connection: URL) {
  const container =
    process.env.RESTORE_DRILL_CONTAINER ??
    (
      await promisify(execFile)("docker", [
        "compose",
        "ps",
        "--quiet",
        "postgres",
      ])
    ).stdout.trim();
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}$/.test(container))
    throw new Error("Local PostgreSQL container unavailable");

  async function run(
    tool: "pg_dump" | "pg_restore",
    database: string,
    file: string,
  ) {
    // Only databases generated by the drill may be passed to native tools.
    if (!/^ts_restore_[a-f0-9]{32}_(source|target)$/.test(database))
      throw new Error("Invalid drill database");
    const dumping = tool === "pg_dump";
    const handle = await open(file, dumping ? "wx" : "r", 0o600);
    try {
      await new Promise<void>((resolve, reject) => {
        const child = spawn(
          "docker",
          [
            "exec",
            "-i",
            "-e",
            "PGPASSWORD",
            "-e",
            "PGUSER",
            container,
            tool,
            "--host=127.0.0.1",
            "--port=5432",
            `--dbname=${database}`,
            "--no-owner",
            "--no-acl",
            ...(dumping
              ? ["--format=custom"]
              : ["--exit-on-error", "--single-transaction"]),
          ],
          {
            // Pass credentials through the environment, never command arguments.
            env: {
              ...process.env,
              PGUSER: decodeURIComponent(connection.username),
              PGPASSWORD: decodeURIComponent(connection.password),
            },
            stdio: dumping
              ? ["ignore", handle.fd, "ignore"]
              : [handle.fd, "ignore", "ignore"],
          },
        );
        const timeout = setTimeout(() => child.kill("SIGKILL"), 120000);
        child.once("error", () => {
          clearTimeout(timeout);
          reject(new Error("PostgreSQL backup tool unavailable"));
        });
        child.once("close", (code) => {
          clearTimeout(timeout);
          if (code === 0) resolve();
          else reject(new Error("PostgreSQL backup tool failed"));
        });
      });
    } finally {
      await handle.close();
    }
  }
  return {
    dump: (database: string, file: string) => run("pg_dump", database, file),
    restore: (database: string, file: string) =>
      run("pg_restore", database, file),
  };
}
